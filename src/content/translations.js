export const formatText = (value, params = {}) =>
  Object.entries(params).reduce(
    (result, [key, replacement]) => result.replaceAll(`{${key}}`, replacement),
    value
  );

export function getTranslation(language, path, params) {
  const locale = translations[language] || translations.en;
  const fallback = translations.en;
  const segments = path.split(".");

  const value = segments.reduce((accumulator, segment) => accumulator?.[segment], locale);
  const fallbackValue = segments.reduce((accumulator, segment) => accumulator?.[segment], fallback);
  const resolved = value ?? fallbackValue;

  if (typeof resolved === "string") {
    return formatText(resolved, params);
  }

  return resolved;
}
